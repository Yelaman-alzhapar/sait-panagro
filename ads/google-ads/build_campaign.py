errors = []


def check(text, limit, where):
    if len(text) > limit:
        errors.append(f"{where}: {len(text)}>{limit} «{text}»")
    return text


def uniq(seq):
    seen, out = set(), []
    for x in seq:
        if x and x.lower() not in seen:
            seen.add(x.lower())
            out.append(x)
    return out


def write(name, header, rows):
    with open(os.path.join(OUT, name), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def main():
    os.makedirs(OUT, exist_ok=True)
    camp_rows, group_rows, kw_rows, ad_rows, neg_rows, loc_rows = [], [], [], [], [], []
    sl_rows, co_rows, sn_rows = [], [], []
    stats = []

    for c in CAMPAIGNS:
        camp_rows.append([c["name"], "Search", "Paused", money(c["budget"]), "Daily",
                          "Manual CPC", "Google search", "ru;kk", "",
                          DAY if c["schedule"] == "day" else "", URL_SUFFIX])
        if c["geo"] == "kz":
            loc_rows.append([c["name"], "2398", "Kazakhstan", ""])
        n_kw = 0
        for g in c["groups"]:
            kk = g.get("lang") == "kk"
            url = SITE + g["url"]
            group_rows.append([c["name"], g["name"], money(g["cpc"]), "Enabled"])
            for k in uniq(g["kw"]):
                for mt in ("Exact", "Phrase"):
                    kw_rows.append([c["name"], g["name"], k, mt, "Enabled", url])
                    n_kw += 1
            heads = uniq(g["h"] + (KK_H if kk else RU_H))[:15]
            descs = uniq(g["d"] + (KK_D if kk else RU_D))[:4]
            for i, h in enumerate(heads):
                check(h, 30, f"{g['name']} H{i + 1}")
            for i, d in enumerate(descs):
                check(d, 90, f"{g['name']} D{i + 1}")
            p1, p2 = g["path"]
            check(p1, 15, f"{g['name']} path1")
            check(p2, 15, f"{g['name']} path2")
            if len(heads) < 3 or len(descs) < 2:
                errors.append(f"{g['name']}: мало заголовков/описаний")
            ad_rows.append([c["name"], g["name"], "Responsive search ad", "Enabled", url, p1, p2]
                           + heads + [""] * (15 - len(heads)) + descs + [""] * (4 - len(descs)))
        for k in uniq(NEG_COMMON + NEG_BY_CAMPAIGN[c["key"]]):
            neg_rows.append([c["name"], k, "Negative Phrase"])
        for t, d1, d2, p in SITELINKS:
            check(t, 25, f"sitelink {t}")
            check(d1, 35, f"sitelink {t} d1")
            check(d2, 35, f"sitelink {t} d2")
            sl_rows.append([c["name"], t, d1, d2, SITE + p])
        for t in CALLOUTS:
            co_rows.append([c["name"], check(t, 25, f"callout {t}")])
        for header, vals in SNIPPETS:
            for v in vals:
                check(v, 25, f"snippet {v}")
            sn_rows.append([c["name"], header, ";".join(vals)])
        stats.append((c["name"], len(c["groups"]), n_kw, c["budget"]))

    if errors:
        print("ОШИБКИ:\n" + "\n".join(errors))
        sys.exit(1)

    write("1-kampanii.csv", ["Campaign", "Campaign Type", "Campaign Status", "Budget", "Budget type",
                             "Bid Strategy Type", "Networks", "Languages", "Start Date",
                             "Ad Schedule", "Final URL suffix"], camp_rows)
    write("2-gruppy.csv", ["Campaign", "Ad Group", "Max CPC", "Ad Group Status"], group_rows)
    write("3-klyuchi.csv", ["Campaign", "Ad Group", "Keyword", "Criterion Type", "Status",
                            "Final URL"], kw_rows)
    write("4-obyavleniya.csv", ["Campaign", "Ad Group", "Ad type", "Status", "Final URL", "Path 1",
                                "Path 2"] + [f"Headline {i}" for i in range(1, 16)]
          + [f"Description {i}" for i in range(1, 5)], ad_rows)
    write("5-minus-slova.csv", ["Campaign", "Keyword", "Criterion Type"], neg_rows)
    write("6-geo.csv", ["Campaign", "Location ID", "Location", "Bid Modifier"], loc_rows)
    write("7-utochneniya.csv", ["Campaign", "Sitelink text", "Description line 1",
                                "Description line 2", "Final URL"], sl_rows)
    write("8-vynoski.csv", ["Campaign", "Callout text"], co_rows)
    write("9-strukturirovannye.csv", ["Campaign", "Header", "Values"], sn_rows)
    with open(os.path.join(OUT, "minus-slova.txt"), "w", encoding="utf-8") as f:
        f.write("# Общий список минус-слов (фразовое соответствие)\n")
        f.write("\n".join(f'"{k}"' for k in uniq(NEG_COMMON)) + "\n")
        for key, lst in NEG_BY_CAMPAIGN.items():
            f.write(f"\n# Дополнительно для кампании: {key}\n")
            f.write("\n".join(f'"{k}"' for k in uniq(lst)) + "\n")

